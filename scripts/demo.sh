#!/usr/bin/env bash
# Reference demo driver.
#
#   ./scripts/demo.sh up               start everything (generates .env with random tokens first)
#   ./scripts/demo.sh bank-outage      bank-api-a fails 90% of authorizations   -> automatic failover
#   ./scripts/demo.sh flaky-bank       bank-api-a fails in bursts (25/3/28/2/31%) -> one incident, intermittent
#   ./scripts/demo.sh bad-deployment   CI ships a broken payment-api            -> rollback after approval
#   ./scripts/demo.sh reset            clear faults and all incident data
#   ./scripts/demo.sh status           list incidents
#   ./scripts/demo.sh approve [ID]     approve the pending remediation (latest incident by default)
#   ./scripts/demo.sh reject  [ID]     reject it
#   ./scripts/demo.sh down             stop and remove containers and volumes
#   ./scripts/demo.sh model dmr|ollama|anthropic|openai|scripted [REASONING_MODEL] [FAST_MODEL]
#                                      choose the model (default: scripted, no API key; see docs/models.md)
#   ./scripts/demo.sh jev local|typesafe|off [shadow|active] [MODEL]
#                                      optional decision model for bounded decisions (docs/decisions.md)
set -euo pipefail
cd "$(dirname "$0")/.."

ENV_FILE=.env
TOKENS=(ONCALL_INGEST_TOKEN ONCALL_GATEWAY_API_TOKEN ONCALL_GATEWAY_APPROVER_TOKEN ONCALL_AGENT_API_TOKEN
        ONCALL_INCIDENT_STATE_MCP_TOKEN ONCALL_OBSERVABILITY_MCP_TOKEN ONCALL_CHANGES_MCP_TOKEN
        ONCALL_REMEDIATION_MCP_TOKEN ONCALL_COMMUNICATIONS_MCP_TOKEN ONCALL_KNOWLEDGE_MCP_TOKEN
        PLATFORM_CHANGES_READ_TOKEN PLATFORM_OPS_TOKEN PLATFORM_DEPLOY_TOKEN CHAOS_TOKEN SLACK_BOT_TOKEN
        POSTGRES_PASSWORD ONCALL_DB_PASSWORD PAYMENTS_DB_PASSWORD)

rand() { head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n'; }

ensure_env() {
  if [[ ! -f $ENV_FILE ]]; then
    echo "Generating $ENV_FILE with random demo tokens (git-ignored)"
    { echo "# Generated by scripts/demo.sh. Local demo only; never commit."
      for t in "${TOKENS[@]}"; do echo "$t=$(rand)"; done
      echo "ONCALL_AGENT_FLAVOR=${ONCALL_AGENT_FLAVOR:-scripted-model}"
    } > "$ENV_FILE"
    chmod 600 "$ENV_FILE"
  fi
}

val() { # value of a token from .env, else the compose default
  local v=""
  [[ -f $ENV_FILE ]] && v=$(grep -E "^$1=" "$ENV_FILE" | tail -1 | cut -d= -f2- || true)
  echo "${v:-$2}"
}

GATEWAY=${GATEWAY_URL:-http://127.0.0.1:7100}
CHAOS=${CHAOS_URL:-http://127.0.0.1:8060}
READ_TOKEN() { val ONCALL_GATEWAY_API_TOKEN demo-only-read; }
APPROVER_TOKEN() { val ONCALL_GATEWAY_APPROVER_TOKEN demo-only-approver; }
CHAOS_TOKEN() { val CHAOS_TOKEN demo-only-chaos; }

json() { python3 -c "import json,sys; d=json.load(sys.stdin); $1"; }

latest_incident() {
  curl -fsS -H "Authorization: Bearer $(READ_TOKEN)" "$GATEWAY/v1/incidents?limit=1" | json 'print(d["incidents"][0]["incident_id"] if d["incidents"] else "")'
}

wait_ready() {
  printf "Waiting for the gateway and the agent"
  for _ in $(seq 1 90); do
    if curl -fsS "$GATEWAY/readyz" 2>/dev/null | grep -q '"ready":true'; then echo " ready."; return 0; fi
    printf "."; sleep 2
  done
  echo; echo "Gateway not ready; check: docker compose logs gateway docker-agent" >&2; return 1
}

decide() {
  local decision=$1 iid=${2:-$(latest_incident)}
  [[ -n $iid ]] || { echo "no incidents" >&2; exit 1; }
  local aid
  aid=$(curl -fsS -H "Authorization: Bearer $(READ_TOKEN)" "$GATEWAY/v1/incidents/$iid" |
        json 'a=[x for x in d.get("actions",[]) if x["status"]=="pending_approval"]; print(a[0]["action_id"] if a else "")')
  [[ -n $aid ]] || { echo "$iid has no action waiting for approval" >&2; exit 1; }
  curl -fsS -X POST -H "Authorization: Bearer $(APPROVER_TOKEN)" -H 'content-type: application/json' \
       -d "{\"by\": \"${USER:-demo-user}\", \"comment\": \"${decision}d from demo.sh\"}" \
       "$GATEWAY/v1/incidents/$iid/actions/$aid/$decision" | json 'print(d["action"]["action"], "->", d["action"]["status"])'
}

set_env() { # set KEY=VALUE in .env, replacing an existing line (portable: no sed -i)
  python3 - "$ENV_FILE" "$1" "$2" <<'PY'
import sys
path, key, value = sys.argv[1:]
lines = [l for l in open(path).read().splitlines() if not l.startswith(key + "=")]
lines.append(f"{key}={value}")
open(path, "w").write("\n".join(lines) + "\n")
PY
}

choose_model() {
  local provider=${1:-} reasoning=${2:-} fast=${3:-} flavor
  ensure_env
  case $provider in
    dmr)
      flavor=dmr; reasoning=${reasoning:-ai/qwen3.6:35b-a3b}; fast=${fast:-$reasoning}
      docker model status >/dev/null 2>&1 || { echo "Docker Model Runner is not available: enable it in Docker Desktop (Settings > AI)." >&2; exit 1; }
      for m in $(printf '%s\n' "$reasoning" "$fast" | sort -u); do echo "Pulling $m (once; large models take a while)"; docker model pull "$m"; done
      ;;
    ollama)
      flavor=ollama; reasoning=${reasoning:-qwen3.6:35b-a3b}; fast=${fast:-$reasoning}
      if command -v ollama >/dev/null; then
        for m in $(printf '%s\n' "$reasoning" "$fast" | sort -u); do echo "Pulling $m"; ollama pull "$m"; done
      else
        echo "ollama CLI not found; make sure the Ollama server on this machine has $reasoning and $fast." >&2
      fi
      echo "Start Ollama with a large context window, e.g.:  OLLAMA_CONTEXT_LENGTH=65536 ollama serve"
      ;;
    anthropic)
      flavor=anthropic; reasoning=${reasoning:-claude-sonnet-5-5}; fast=${fast:-claude-haiku-5-5}
      grep -q '^ANTHROPIC_API_KEY=.' "$ENV_FILE" || echo "Add ANTHROPIC_API_KEY=... to .env" >&2
      ;;
    openai)
      flavor=openai; reasoning=${reasoning:?give the reasoning model id}; fast=${fast:-$reasoning}
      grep -q '^OPENAI_API_KEY=.' "$ENV_FILE" || echo "Add OPENAI_API_KEY=... to .env" >&2
      ;;
    scripted)
      flavor=scripted-model
      ;;
    *) echo "usage: $0 model dmr|ollama|anthropic|openai|scripted [REASONING_MODEL] [FAST_MODEL]" >&2; exit 1 ;;
  esac
  set_env ONCALL_AGENT_FLAVOR "$flavor"
  [[ -n $reasoning ]] && set_env ONCALL_REASONING_MODEL "$reasoning"
  [[ -n $fast ]] && set_env ONCALL_FAST_MODEL "$fast"
  echo "Model: $flavor${reasoning:+ (reasoning=$reasoning, fast=$fast)}"
  if docker compose ps --status running --services 2>/dev/null | grep -qx docker-agent; then
    docker compose up -d docker-agent
  fi
}

choose_jev() {
  local where=${1:-} mode=${2:-shadow} model=${3:-}
  ensure_env
  case $where in
    local)
      model=${model:-nimble}
      if command -v ollama >/dev/null; then echo "Pulling $model (Ollama >= 0.35)"; ollama pull "$model"
      else echo "ollama CLI not found; make sure the Ollama server on this machine has $model (Ollama >= 0.35)." >&2; fi
      set_env ONCALL_JEV_ENABLED true; set_env ONCALL_JEV_PROVIDER ollama
      set_env ONCALL_JEV_URL http://host.docker.internal:11434/v1; set_env ONCALL_JEV_MODEL "$model"
      set_env ONCALL_JEV_ALLOW_EXTERNAL false
      ;;
    typesafe)
      model=${model:-jev-latest}
      grep -q '^ONCALL_JEV_API_KEY=.' "$ENV_FILE" || echo "Add ONCALL_JEV_API_KEY=... to .env" >&2
      echo "Incident text will be sent to api.typesafe.ai (ONCALL_JEV_ALLOW_EXTERNAL=true)."
      set_env ONCALL_JEV_ENABLED true; set_env ONCALL_JEV_PROVIDER typesafe
      set_env ONCALL_JEV_URL https://api.typesafe.ai/v1; set_env ONCALL_JEV_MODEL "$model"
      set_env ONCALL_JEV_ALLOW_EXTERNAL true
      ;;
    off) set_env ONCALL_JEV_ENABLED false ;;
    *) echo "usage: $0 jev local|typesafe|off [shadow|active] [MODEL]" >&2; exit 1 ;;
  esac
  if [[ $where != off ]]; then
    [[ $mode == shadow || $mode == active ]] || { echo "mode must be shadow or active" >&2; exit 1; }
    if [[ $mode == active ]]; then
      echo "Active mode needs per-decision min_confidence in demo/config/oncall.yaml (decisions.per_decision);" >&2
      echo "set it from shadow-mode data first. See docs/decisions.md." >&2
    fi
    set_env ONCALL_JEV_MODE "$mode"
    echo "Decision model: $where ($model), $mode mode"
  else
    echo "Decision model: off"
  fi
  if docker compose ps --status running --services 2>/dev/null | grep -q '^mcp-'; then
    docker compose up -d mcp-incident-state mcp-knowledge mcp-remediation
  fi
}

case "${1:-help}" in
  up)
    ensure_env
    docker compose up -d --build
    wait_ready
    cat <<MSG

  Dashboard   http://localhost:3000
  Gateway     http://localhost:7100/v1/incidents   (Bearer token in .env: ONCALL_GATEWAY_API_TOKEN)
  Prometheus  http://localhost:9090
  Slack sim   http://localhost:8070/channels

  Try: ./scripts/demo.sh bank-outage
MSG
    ;;
  down) docker compose down -v ;;
  bank-outage|flaky-bank|bad-deployment|fraud-outage)
    curl -fsS -X POST -H "Authorization: Bearer $(CHAOS_TOKEN)" "$CHAOS/v1/scenarios/$1" | json 'print("started:", d["started"], "-", d["description"])'
    echo "Watch it at http://localhost:3000 (or: ./scripts/demo.sh status)"
    ;;
  reset)
    curl -fsS -X POST -H "Authorization: Bearer $(CHAOS_TOKEN)" "$CHAOS/v1/reset" | json 'print("reset:", d["results"])'
    ;;
  status)
    curl -fsS -H "Authorization: Bearer $(READ_TOKEN)" "$GATEWAY/v1/incidents" |
      json '[print("%-22s %-5s %-22s %s" % (i["incident_id"], i["severity"], i["status"], i["summary"])) for i in d["incidents"]] or print("no incidents")'
    ;;
  model) choose_model "${2:-}" "${3:-}" "${4:-}" ;;
  jev) choose_jev "${2:-}" "${3:-}" "${4:-}" ;;
  approve) decide approve "${2:-}" ;;
  reject) decide reject "${2:-}" ;;
  *) sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//' ;;
esac
